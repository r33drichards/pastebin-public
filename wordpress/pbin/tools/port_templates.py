#!/usr/bin/env python3
"""Generate reviewable PHP templates/assets from the repository's Go frontend.

This is a build-time, narrow syntax conversion, not a runtime template engine.
Unknown template operations fail closed. Generated PHP uses explicit context
escaping: JSON in script blocks and HTML elsewhere. Review generated changes
when updating the upstream frontend. No eval or request-selected include exists.
"""
from pathlib import Path
import re
import shutil

PLUGIN = Path(__file__).resolve().parents[1]
ROOT = PLUGIN.parents[1]


def convert(source: str) -> str:
    # Rewrite trusted literal endpoint URLs, before substituting user values.
    source = re.sub(
        r'''(["'`])/(static/|paste(?=[?"'`])|diff(?=[?"'`])|snapshot(?=[?"'`])|snapshots(?=[?"'`])|html(?=[?"'`])|collab(?=[?"'`])|complete(?=[?"'`]))''',
        lambda m: m[1] + "<?= pbin_html(pbin_path('/" + m[2] + "')) ?>",
        source,
    )
    source = source.replace('href="/"', 'href="<?= pbin_html(pbin_path(\'/\')) ?>"')
    output, cursor, stack = [], 0, []
    for token in re.finditer(r'{{\s*(.*?)\s*}}', source):
        prefix = source[cursor:token.start()]
        expression = token[1]
        variable = '$entry' if 'range' in stack else '$data'
        in_script = source.rfind('<script', 0, token.start()) > source.rfind('</script', 0, token.start())
        if re.fullmatch(r'\.[A-Za-z]+', expression):
            field = expression[1:]
            if in_script:
                # Go html/template supports both a bare JS value and a value
                # embedded between quotes. PHP emits one complete JSON string.
                if prefix.endswith('"') and source[token.end():token.end()+1] == '"':
                    prefix = prefix[:-1]
                    cursor = token.end() + 1
                else:
                    cursor = token.end()
                result = f"<?= pbin_json({variable}['{field}'] ?? '') ?>"
            else:
                cursor = token.end()
                result = f"<?= pbin_html({variable}['{field}'] ?? '') ?>"
        elif expression.startswith('if '):
            expr = expression[3:]
            if expr == 'eq .Language "markdown"':
                condition = f"({variable}['Language'] ?? '') === 'markdown'"
            elif re.fullmatch(r'\.[A-Za-z]+', expr):
                field = expr[1:]
                condition = f"!empty({variable}['{field}'])" if field == 'Snapshots' else f"({variable}['{field}'] ?? '') !== ''"
            else:
                raise ValueError(f'Unsupported condition: {expr}')
            result = f'<?php if ({condition}): ?>'
            stack.append('if')
            cursor = token.end()
        elif expression == 'range .Snapshots':
            result = "<?php foreach (($data['Snapshots'] ?? []) as $entry): ?>"
            stack.append('range')
            cursor = token.end()
        elif expression == 'else':
            if not stack or stack[-1] != 'if':
                raise ValueError('Unexpected else')
            result = '<?php else: ?>'
            cursor = token.end()
        elif expression == 'end':
            result = '<?php ' + ('endforeach' if stack.pop() == 'range' else 'endif') + '; ?>'
            cursor = token.end()
        else:
            raise ValueError(f'Unsupported template operation: {expression}')
        output.extend([prefix, result])
    output.append(source[cursor:])
    if stack:
        raise ValueError('Unclosed template block')
    return "<?php defined('ABSPATH') || exit; /* Generated by tools/port_templates.py; review context escaping on updates. */ ?>\n" + ''.join(output)


def main():
    for name in ('paste', 'diff', 'diff-share', 'snapshot', 'snapshots'):
        source = (ROOT / 'templates' / (name + '.html')).read_text()
        if name == 'paste':
            start = source.index('    // Opening a paste joins its room:')
            end = source.index('    // Function to update format button visibility', start)
            source = source[:start] + (PLUGIN / 'tools/single-user-editor.js').read_text() + source[end:]
            source = source.replace('      if (isLive()) collab.setLanguage(newLanguage);', '')
            source = re.sub(r'      <!-- live collaboration:.*?</div>', '<button type="button" id="saveStatus" class="pb-btn" title="Single-user editing. Other tabs do not synchronize; the last save wins.">Saved · single-user editing</button>', source, count=1, flags=re.S)
            source = source.replace('  <script src="/static/js/collab.js"></script>', '')
            source = source.replace('Live collaborative editing,', 'Single-user editing with HTTP autosave,').replace('collaborative pastebin with live code execution', 'pastebin with browser code execution')
        (PLUGIN / 'templates' / (name + '.php')).write_text(convert(source))
    shutil.copytree(ROOT / 'static', PLUGIN / 'static', dirs_exist_ok=True)
    (PLUGIN / 'static/js/collab.js').unlink(missing_ok=True)
    main_go = (ROOT / 'main.go').read_text()
    css = main_go.split('<style>', 1)[1].split('</style>', 1)[0]
    (PLUGIN / 'static/css/markdown.css').write_text('\n'.join(line.rstrip() for line in css.strip().splitlines()) + '\n')


if __name__ == '__main__':
    main()
